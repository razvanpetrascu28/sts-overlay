using System.Reflection;
using System.Runtime.CompilerServices;

internal static class ObserverChecks
{
    internal static void Run(Assembly game, Assembly mod)
    {
        const BindingFlags fields = BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic;
        Type Game(string name) => game.GetType("MegaCrit.Sts2.Core." + name, true)!;
        object Raw(Type type) => RuntimeHelpers.GetUninitializedObject(type);
        void Set(object target, string field, object? value) => target.GetType().GetField(field, fields)!.SetValue(target, value);
        object Call(object target, string name, params object?[] args) => target.GetType().GetMethod(name, fields)!.Invoke(target, args)!;
        void Equal(long expected, long actual, string name)
        {
            if (expected != actual) throw new Exception($"{name}: expected {expected}, got {actual}");
            Console.WriteLine("PASS observer " + name);
        }

        // These deliberately minimal fixtures live only in this isolated test process.
        // No game initialization, files, saves, network or Godot native calls are involved.
        Type playerType = Game("Entities.Players.Player");
        Type creatureType = Game("Entities.Creatures.Creature");
        Type combatType = Game("Combat.CombatState");
        Type sideType = Game("Combat.CombatSide");
        Type propsType = Game("ValueProps.ValueProp");
        object props = Enum.ToObject(propsType, 0);
        object combat = Raw(combatType);
        Set(combat, "<RoundNumber>k__BackingField", 1);
        object Player(ulong id)
        {
            object player = Raw(playerType); Set(player, "<NetId>k__BackingField", id); return player;
        }
        object Creature(object player)
        {
            object c = Activator.CreateInstance(creatureType, player, 50, 80)!;
            Set(c, "<CombatState>k__BackingField", combat); return c;
        }
        object alice = Creature(Player(1)); object bob = Creature(Player(2));
        object enemy = Raw(creatureType);
        Set(enemy, "<Side>k__BackingField", Enum.Parse(sideType, "Enemy"));
        Set(enemy, "<CombatState>k__BackingField", combat); Set(enemy, "_currentHp", 20); Set(enemy, "_maxHp", 20);

        Type tracker = mod.GetType("StsOverlay.GameTracker", true)!;
        const BindingFlags statics = BindingFlags.Static | BindingFlags.Public | BindingFlags.NonPublic;
        dynamic stats = tracker.GetField("Stats", statics)!.GetValue(null)!;
        tracker.GetField("<Combat>k__BackingField", statics)!.SetValue(null, combat);
        stats.Begin("observer-run", "observer-fight", new Dictionary<string, string> { ["1"] = "Alice", ["2"] = "Bob" });
        object ambient = tracker.GetField("Ambient", statics)!.GetValue(null)!;
        Type sourceType = mod.GetType("StsOverlay.EffectSource", true)!;
        object source = Activator.CreateInstance(sourceType, "1", "defend-ally", false)!;
        ambient.GetType().GetProperty("Value")!.SetValue(ambient, source);

        Call(bob, "GainBlockInternal", 15m);
        Equal(15, (long)stats.Current.Players["1"].Total.BlockGenerated, "actual block generated by another player");
        decimal blocked = (decimal)Call(bob, "DamageBlockInternal", 20m, props);
        Equal(15, (long)blocked, "game resolves absorbed damage");
        Equal(15, (long)stats.Current.Players["1"].Cards["defend-ally"].BlockUsed, "source card gets consumed block credit");

        object history = Activator.CreateInstance(Game("Combat.History.CombatHistory"))!;
        void DamageEvent(object receiver, object dealer, object result)
        {
            object entry = Activator.CreateInstance(Game("Combat.History.Entries.DamageReceivedEntry"),
                result, receiver, dealer, null, 1, Enum.Parse(sideType, "Player"), history, Array.CreateInstance(playerType, 0))!;
            Call(history, "Add", combat, entry);
        }
        object incoming = Call(bob, "LoseHpInternal", 5m, props);
        incoming.GetType().GetProperty("BlockedDamage")!.SetValue(incoming, 15);
        DamageEvent(bob, enemy, incoming);
        Equal(5, (long)stats.Current.Players["2"].Total.DamageTaken, "actual player HP loss from history");
        Equal(15, (long)stats.Current.Players["2"].Total.DamageBlocked, "exact player blocked damage from history");

        Call(bob, "HealInternal", 100m);
        Equal(35, (long)stats.Current.Players["1"].Total.AllyHealing, "effective ally healing excludes overheal");
        object dealt = Call(enemy, "LoseHpInternal", 100m, props);
        DamageEvent(enemy, alice, dealt);
        Equal(20, (long)stats.Current.Players["1"].Total.Damage, "enemy HP removed excludes overkill");
        Equal(0, (long)stats.Current.Players["2"].Total.Damage, "teammate damage stays separate");
        Console.WriteLine("8 real game observer checks passed with two simulated players.");
    }
}
